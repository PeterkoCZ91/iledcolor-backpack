    // ── Conditional XOR/ADD mixing ──────────────────────────────

    private fun condMix(state: IntArray, keyBlock: IntArray, mask: Int, phase: Int): IntArray {
        val result = state.copyOf()
        for (i in 0 until 16) {
            val bitSet = ((1 shl i) and mask) != 0
            if (phase == 3) {
                result[i] = if (bitSet) (result[i] xor keyBlock[i]) else ((keyBlock[i] + result[i]) and 0xFF)
            } else {
                result[i] = if (bitSet) ((keyBlock[i] + result[i]) and 0xFF) else (result[i] xor keyBlock[i])
            }
        }
        return result
    }

    // ── S-box substitution ──────────────────────────────────────

    private fun sboxSub(state: IntArray): IntArray {
        val result = state.copyOf()
        for (pos in intArrayOf(0, 3, 4, 7, 8, 11, 12, 15)) result[pos] = SBOX[result[pos]]
        for (pos in intArrayOf(1, 2, 5, 6, 9, 10, 13, 14)) result[pos] = ISBOX[result[pos]]
        return result
    }

    // ── Block cipher (sub_11b8) ─────────────────────────────────

    private fun blockCipher(stateIn: IntArray, ek: IntArray, mode: Int): IntArray {
        var s = stateIn.copyOf()
        val initial = stateIn.copyOf()

        // x9=0: Phase3 + Sbox + Phase5 (before any Fibonacci)
        s = condMix(s, ek.sliceArray(0 until 16), MASK, 3)
        s = sboxSub(s)
        s = condMix(s, ek.sliceArray(16 until 32), MASK, 5)

        for (x9 in 1..8) {
            s = fibonacciMix(s)
            val ekOff = x9 * 0x20

            if (x9 == 8) {
                // Final mixing
                s = condMix(s, ek.sliceArray(0x100 until 0x110), MASK, 3)
                break
            }

            // Phase 2 at x9==2 when mode!=0
            if (mode != 0 && x9 == 2) {
                for (i in 0 until 16) {
                    val bitSet = ((1 shl i) and MASK) != 0
                    s[i] = if (bitSet) (s[i] xor initial[i]) else ((initial[i] + s[i]) and 0xFF)
                }
            }

            s = condMix(s, ek.sliceArray(ekOff until ekOff + 16), MASK, 3)
            s = sboxSub(s)
            s = condMix(s, ek.sliceArray(ekOff + 16 until ekOff + 32), MASK, 5)
        }

        return s
    }

    // ── functionE1test (0xacc) ─────────────────────────────────

    fun functionE1test(key6: IntArray, input16: IntArray, seed16: IntArray): IntArray {
        val expandedKey = IntArray(16) { key6[it % 6] }
        val output = input16.copyOfRange(0, 16)

        val ks1 = keySchedule(seed16.copyOfRange(0, 16))
        val cipherOut = blockCipher(output, ks1, 0).copyOf()

        for (i in 0 until 16) {
            cipherOut[i] = (expandedKey[i] + (cipherOut[i] xor input16[i])) and 0xFF
        }

        val obf = intArrayOf(
            (seed16[0] - 0x17) and 0xFF, seed16[1] xor 0xE5,
            (seed16[2] - 0x21) and 0xFF, seed16[3] xor 0xC1,
            (seed16[4] - 0x4D) and 0xFF, seed16[5] xor 0xA7,
            (seed16[6] - 0x6B) and 0xFF, seed16[7] xor 0x83,
            seed16[8] xor 0xE9,          (seed16[9] - 0x1B) and 0xFF,
            seed16[10] xor 0xDF,         (seed16[11] - 0x3F) and 0xFF,
            seed16[12] xor 0xB3,         (seed16[13] - 0x59) and 0xFF,
            seed16[14] xor 0x95,         (seed16[15] - 0x7D) and 0xFF
        )

        val ks2 = keySchedule(obf)
        return blockCipher(cipherOut, ks2, 1)
    }

    // ── Public API ──────────────────────────────────────────────

    /** Build a [0x00, rand*16] auth init packet (17 bytes). */
    fun getRandomAuthData(): ByteArray {
        val result = ByteArray(17)
        result[0] = 0x00
        val rnd = ByteArray(16)
        java.security.SecureRandom().nextBytes(rnd)
        System.arraycopy(rnd, 0, result, 1, 16)
        return result
    }

    /** Encrypt a device challenge [0x00/0x01, challenge*16] -> [0x01, encrypted*16]. */
    fun getEncryptedAuthData(deviceData17: ByteArray): ByteArray {
        val input16 = IntArray(16) { deviceData17[it + 1].toInt() and 0xFF }
        val encrypted = functionE1test(MAGIC, input16, STATIC_KEY)
        val result = ByteArray(17)
        result[0] = 0x01
        for (i in 0 until 16) result[i + 1] = encrypted[i].toByte()
        return result
    }
