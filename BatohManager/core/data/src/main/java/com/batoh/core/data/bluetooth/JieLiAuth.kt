    // ── Key schedule (sub_1038) ─────────────────────────────────

    private fun keySchedule(data16: IntArray): IntArray {
        val out = IntArray(272)
        for (i in 0 until 16) out[i] = data16[i]

        val buf = IntArray(17)
        for (i in 0 until 16) buf[i] = data16[i]
        var checksum = 0
        for (b in data16) checksum = checksum xor b
        buf[16] = checksum and 0xFF

        for (rnd in 0 until 16) {
            for (i in 0 until 17) {
                val b = buf[i]
                buf[i] = ((b shl 3) or (b ushr 5)) and 0xFF
            }
            var readPos = (rnd + 1) % 17
            for (j in 0 until 16) {
                val src = buf[readPos]
                val tblIdx = 0x0F + rnd * 16 - j
                out[16 + rnd * 16 + j] = (KS_TABLE[tblIdx] + src) and 0xFF
                readPos += 1
                if (readPos > 16) readPos = 0
            }
        }
        return out
    }

